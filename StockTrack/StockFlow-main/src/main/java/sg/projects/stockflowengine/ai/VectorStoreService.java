package sg.projects.stockflowengine.ai;

import org.springframework.ai.document.Document;
import org.springframework.ai.vectorstore.SearchRequest;
import org.springframework.ai.vectorstore.VectorStore;
import org.springframework.stereotype.Service;
import sg.projects.stockflowengine.dto.MaterialVariantStockDto;
import sg.projects.stockflowengine.model.Inward;
import sg.projects.stockflowengine.model.Material;
import sg.projects.stockflowengine.model.MaterialVariant;
import sg.projects.stockflowengine.model.Outward;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;

/**
 * Service responsible for converting warehouse domain objects into vector embeddings
 * and performing semantic similarity search via PGVector.
 *
 * <p>Acts as the bridge between warehouse data and the AI layer:
 * <ul>
 *   <li>Converts domain objects to structured text documents</li>
 *   <li>Stores embeddings in PostgreSQL via PGVector extension</li>
 *   <li>Performs semantic similarity search using HNSW index with COSINE_DISTANCE</li>
 * </ul>
 *
 * <p>Embedding is triggered in two ways:
 * <ol>
 *   <li>Startup — {@link StockDataInitializer} bulk embeds all existing data</li>
 *   <li>Real-time — {@link WarehouseEventListener} embeds on every create/update</li>
 * </ol>
 *
 * <p>Embeddings are generated by nomic-embed-text (768 dimensions) running
 * locally via Ollama — no data leaves the system.
 *
 * @see WarehouseEventListener
 * @see StockDataInitializer
 * @see StockAiService
 */
@Service
public class VectorStoreService {

    private final VectorStore vectorStore;

    /**
     * Constructs VectorStoreService with Spring AI's auto-configured PGVector store.
     *
     * @param vectorStore Spring AI VectorStore backed by PostgreSQL PGVector extension
     */
    public VectorStoreService(VectorStore vectorStore) {
        this.vectorStore = vectorStore;
    }

    /**
     * Bulk embeds a list of stock level DTOs into PGVector.
     * Used by {@link StockDataInitializer} on startup.
     *
     * @param stockList list of stock level DTOs to embed
     */
    public void embedStockData(List<MaterialVariantStockDto> stockList) {
        List<Document> documents = new ArrayList<>();
        for (MaterialVariantStockDto stock : stockList) {
            String content = String.format(
                    "Variant: %s | Total Inward: %d | Total Outward: %d | Current Stock: %d",
                    stock.getMaterialVariantName(),
                    stock.getTotalInward(),
                    stock.getTotalOutward(),
                    stock.getCurrentStock()
            );
            documents.add(new Document(content, Map.of("type", "stock")));
        }
        vectorStore.add(documents);
    }

    /**
     * Bulk embeds a list of inward records into PGVector.
     * Used by {@link StockDataInitializer} on startup.
     *
     * @param inwards list of inward transactions to embed
     */
    public void embedInwards(List<Inward> inwards) {
        List<Document> documents = new ArrayList<>();
        for (Inward inward : inwards) {
            String content = String.format(
                    "InwardID: %d | VariantID: %d | Quantity: %d | Status: %s | Date: %s | By: %s | Condition: %s",
                    inward.getInwardId(),
                    inward.getMaterialVariantId(),
                    inward.getQuantity(),
                    inward.getStatus(),
                    inward.getInwardDate(),
                    inward.getInwardBy(),
                    inward.getItemCondition()
            );
            documents.add(new Document(content, Map.of("type", "inward")));
        }
        vectorStore.add(documents);
    }

    /**
     * Bulk embeds a list of outward records into PGVector.
     * Used by {@link StockDataInitializer} on startup.
     *
     * @param outwards list of outward transactions to embed
     */
    public void embedOutwards(List<Outward> outwards) {
        List<Document> documents = new ArrayList<>();
        for (Outward outward : outwards) {
            String content = String.format(
                    "OutwardID: %d | VariantID: %d | CustomerID: %d | Quantity: %d | Status: %s | Date: %s | By: %s",
                    outward.getOutwardId(),
                    outward.getMaterialVariantId(),
                    outward.getCustomerId(),
                    outward.getQuantity(),
                    outward.getStatus(),
                    outward.getOutwardDate(),
                    outward.getOutwardBy()
            );
            documents.add(new Document(content, Map.of("type", "outward")));
        }
        vectorStore.add(documents);
    }

    /**
     * Performs semantic similarity search against PGVector store.
     *
     * <p>Converts the query to a vector embedding via nomic-embed-text,
     * then searches for the top 5 most similar documents using HNSW index
     * with COSINE_DISTANCE. Only returns documents with 50%+ similarity.
     *
     * @param query natural language search query from the user
     * @return list of up to 5 most semantically relevant warehouse documents
     */
    public List<Document> search(String query) {
        return vectorStore.similaritySearch(
                SearchRequest.builder()
                        .query(query)
                        .topK(5)              // return top 5 most relevant
                        .similarityThreshold(0.5) // only return if 50%+ similar
                        .build()
        );
    }

    /**
     * Embeds a single inward record into PGVector.
     * Called by {@link WarehouseEventListener} on inward create or status change.
     *
     * @param inward the inward transaction to embed
     */
    public void embedInward(Inward inward) {
        String content = String.format(
                "InwardID: %d | VariantID: %d | Quantity: %d | Status: %s | Date: %s | By: %s | Condition: %s",
                inward.getInwardId(),
                inward.getMaterialVariantId(),
                inward.getQuantity(),
                inward.getStatus(),
                inward.getInwardDate(),
                inward.getInwardBy(),
                inward.getItemCondition()
        );
        vectorStore.add(List.of(new Document(content,
                Map.of("type", "inward", "id", inward.getInwardId().toString())
        )));
    }

    /**
     * Embeds a single outward record into PGVector.
     * Called by {@link WarehouseEventListener} on outward create or completion.
     *
     * @param outward the outward transaction to embed
     */
    public void embedOutward(Outward outward) {
        String content = String.format(
                "OutwardID: %d | VariantID: %d | CustomerID: %d | Quantity: %d | Status: %s | Date: %s | By: %s",
                outward.getOutwardId(),
                outward.getMaterialVariantId(),
                outward.getCustomerId(),
                outward.getQuantity(),
                outward.getStatus(),
                outward.getOutwardDate(),
                outward.getOutwardBy()
        );
        vectorStore.add(List.of(new Document(content,
                Map.of("type", "outward", "id", outward.getOutwardId().toString())
        )));
    }

    /**
     * Embeds a single material record into PGVector.
     * Called by {@link WarehouseEventListener} on material create, update or deactivation.
     *
     * @param material the material to embed
     */
    public void embedMaterial(Material material) {
        String content = String.format(
                "MaterialID: %d | Name: %s | Description: %s | Status: %s",
                material.getMaterialId(),
                material.getMaterialName(),
                material.getDescription(),
                material.getStatus()
        );
        vectorStore.add(List.of(new Document(content,
                Map.of("type", "material", "id", material.getMaterialId().toString())
        )));
    }

    /**
     * Embeds a single material variant record into PGVector.
     * Called by {@link WarehouseEventListener} on variant create, update or deactivation.
     *
     * @param variant the material variant to embed
     */
    public void embedVariant(MaterialVariant variant) {
        String content = String.format(
                "VariantID: %d | MaterialID: %d | Name: %s | Status: %s",
                variant.getMaterialVariantId(),
                variant.getMaterialId(),
                variant.getMaterialVariantName(),
                variant.getStatus()
        );
        vectorStore.add(List.of(new Document(content,
                Map.of("type", "variant", "id", variant.getMaterialVariantId().toString())
        )));
    }

    /**
     * Embeds current stock level for a single variant into PGVector.
     * Called by {@link WarehouseEventListener} after inward approval or outward completion
     * to keep stock levels in vector store synchronized with actual calculated stock.
     *
     * @param stock the stock level DTO containing variant name and calculated counts
     */
    public void embedStockForVariant(MaterialVariantStockDto stock) {
        String content = String.format(
                "Variant: %s | Total Inward: %d | Total Outward: %d | Current Stock: %d",
                stock.getMaterialVariantName(),
                stock.getTotalInward(),
                stock.getTotalOutward(),
                stock.getCurrentStock()
        );
        vectorStore.add(List.of(new Document(content,
                Map.of("type", "stock", "variantId",
                        stock.getMaterialVariantId().toString())
        )));
    }
}